use std::{env, fs, path::PathBuf};

fn main() {
    println!("cargo:rerun-if-env-changed=DESK_UPDATE_PUBLIC_KEY");
    println!("cargo:rerun-if-env-changed=DESK_UPDATE_REPOSITORY");
    println!("cargo:rerun-if-changed=../config/config.json");
    println!("cargo:rerun-if-changed=../config/config.example.json");
    println!("cargo:rerun-if-changed=../config/apps.json");
    println!("cargo:rerun-if-changed=../dist-tauri/config.json");

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let dest_path = out_dir.join("bundled_config.json");

    let candidates = [
        PathBuf::from("../dist-tauri/config.json"),
        PathBuf::from("../config/config.json"),
        PathBuf::from("../config/apps.json"),
        PathBuf::from("../config/config.example.json"),
    ];

    let mut found = false;
    for candidate in &candidates {
        if candidate.is_file() {
            if let Ok(content) = fs::read_to_string(candidate) {
                if fs::write(&dest_path, content).is_ok() {
                    found = true;
                    break;
                }
            }
        }
    }

    if !found {
        let fallback = r#"{"schemaVersion":1,"name":"AWS Environment Desk","productName":"AWS Environment Desk","apps":[]}"#;
        let _ = fs::write(&dest_path, fallback);
    }

    // Ensure icon and frontend distribution paths exist for compile-time macros and resource bundling
    let icons_dir = PathBuf::from("../dist/icons");
    let dist_tauri_dir = PathBuf::from("../dist-tauri");
    let _ = fs::create_dir_all(&icons_dir);
    let _ = fs::create_dir_all(&dist_tauri_dir);

    const PNG_1X1: &[u8] = &[
        0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48,
        0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00,
        0x00, 0x1f, 0x15, 0xc4, 0x89, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x44, 0x41, 0x54, 0x78,
        0x9c, 0x63, 0x60, 0x00, 0x00, 0x00, 0x02, 0x00, 0x01, 0xe5, 0x27, 0xbc, 0x33, 0x00,
        0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
    ];

    const ICO_1X1: &[u8] = &[
        0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x20, 0x00,
        0x43, 0x00, 0x00, 0x00, 0x16, 0x00, 0x00, 0x00, 0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a,
        0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01,
        0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4, 0x89, 0x00,
        0x00, 0x00, 0x0d, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0x60, 0x00, 0x00, 0x00,
        0x02, 0x00, 0x01, 0xe5, 0x27, 0xbc, 0x33, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e,
        0x44, 0xae, 0x42, 0x60, 0x82,
    ];

    const ICNS_1X1: &[u8] = &[
        0x69, 0x63, 0x6e, 0x73, 0x00, 0x00, 0x00, 0x53, 0x69, 0x63, 0x70, 0x34, 0x00, 0x00,
        0x00, 0x4b, 0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d,
        0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06,
        0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4, 0x89, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x44, 0x41,
        0x54, 0x78, 0x9c, 0x63, 0x60, 0x00, 0x00, 0x00, 0x02, 0x00, 0x01, 0xe5, 0x27, 0xbc,
        0x33, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
    ];

    let png_files = [
        "trayTemplate.png",
        "trayTemplate@2x.png",
        "tray.png",
        "tray@2x.png",
        "icon.png",
        "Square150x150Logo.png",
    ];
    for name in &png_files {
        let path = icons_dir.join(name);
        if !path.exists() {
            let _ = fs::write(&path, PNG_1X1);
        }
    }

    let ico_path = icons_dir.join("icon.ico");
    if !ico_path.exists() {
        let _ = fs::write(&ico_path, ICO_1X1);
    }

    let icns_path = icons_dir.join("icon.icns");
    if !icns_path.exists() {
        let _ = fs::write(&icns_path, ICNS_1X1);
    }

    let index_html = dist_tauri_dir.join("index.html");
    if !index_html.exists() {
        let _ = fs::write(&index_html, "<!DOCTYPE html><html><body></body></html>");
    }

    tauri_build::build();
}
